#!/usr/bin/env python3
"""Embed the selected boot logo losslessly using LVGL's existing LZ4 decoder."""
from pathlib import Path
import struct

from PIL import Image
import lz4.block
from esphome.components.image import ImageRGB565

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/branding/jarvis-neural-orb-v1.png'
HEADER = ROOT / 'styles/glass-v2/boot_logo.h'


def pixels():
    # Match ESPHome's file-image resize and encoder, including byte order.
    encoder = ImageRGB565(320, 320, 'opaque', None, False)
    encoder.set_big_endian(False)
    image = encoder.convert(Image.open(SOURCE).resize((320, 320)), SOURCE)
    for pixel in image.get_flattened_data():
        encoder.encode(pixel)
    return bytes(encoder.data)


def generate():
    raw = pixels()
    compressed = lz4.block.compress(raw, mode='high_compression', compression=12, store_size=False)
    data = struct.pack('<III', 2, len(compressed), len(raw)) + compressed
    rows = '\n'.join('  ' + ','.join(f'0x{n:02x}' for n in data[i:i+24]) + ','
                     for i in range(0, len(data), 24))
    return '''// Generated by tools/pack_boot_logo.py; do not edit the pixel payload.
#pragma once
#include "lvgl.h"
#if !LV_USE_LZ4 || !LV_USE_LZ4_INTERNAL || !LV_BIN_DECODER_RAM_LOAD
#error "Boot logo requires LVGL's native LZ4 decoder"
#endif
namespace boot_brand {
inline constexpr uint8_t data[] = {
''' + rows + '''
};
inline const lv_image_dsc_t *image() {
  static const lv_image_dsc_t descriptor = [] {
    lv_image_dsc_t d{};
    d.header.magic = LV_IMAGE_HEADER_MAGIC;
    d.header.cf = LV_COLOR_FORMAT_RGB565;
    d.header.flags = LV_IMAGE_FLAGS_COMPRESSED;
    d.header.w = d.header.h = 320;
    d.header.stride = 640;
    d.data_size = sizeof(data);
    d.data = data;
    return d;
  }();
  return &descriptor;
}
}  // namespace boot_brand
'''


if __name__ == '__main__':
    HEADER.write_text(generate())
    print(HEADER)
